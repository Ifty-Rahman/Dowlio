import DowlioCore
import DowlioMedia
import DowlioTestSupport
import Foundation
import Testing

@Suite(.timeLimit(.minutes(1)))
struct SubtitleTests {
    private let watch = URL(string: "https://www.youtube.com/watch?v=plN7JMbadRg")!

    private func candidate(_ fixture: String, languages: [String], downloads: Bool = true) async throws -> Candidate {
        let standIn = try await YTDLPStandIn.printing(fixture)
        let preference = SubtitlePreference(downloads: downloads, languages: languages)
        let analyzer = PageAnalyzer(readers: [], ytdlp: YTDLPRunner(installer: standIn.installer), subtitles: { preference }) { _, _ in
            throw URLError(.cannotConnectToHost)
        }
        var last: PageAnalysis?
        for await update in analyzer.analyze(SentPage(url: watch)) { last = update }
        guard case .found(let candidates)? = last, let first = candidates.first else { throw FoundNothing() }
        return first
    }

    private struct FoundNothing: Error {}

    private func subtitles(of version: Version?) -> [MediaExtras.Subtitle] {
        guard case .media(let media)? = version?.source else { return [] }
        return media.extras?.subtitles ?? []
    }

    private func fixtureURL(_ fixture: String, _ kind: String, _ key: String, translation: Bool = false) throws -> URL? {
        let data = try Data(contentsOf: YTDLPStandIn.fixture(fixture))
        let json = try JSONSerialization.jsonObject(with: data) as? [String: Any]
        let tracks = (json?[kind] as? [String: [[String: String]]])?[key] ?? []
        return tracks.first { $0["ext"] == "vtt" && ($0["url"]?.contains("tlang=") ?? false) == translation }.flatMap { URL(string: $0["url"] ?? "") }
    }

    @Test func eachChosenLanguageTakesTheUploadersSubtitles() async throws {
        let video = try await candidate("video-subtitles-chapters.json", languages: ["en", "bn"])

        let chosen = subtitles(of: video.versions.first { !$0.isAudio })
        #expect(chosen.map(\.language) == ["en", "bn"])
        #expect(chosen.allSatisfy { $0.format == "vtt" })
        #expect(chosen.first?.url == (try fixtureURL("video-subtitles-chapters.json", "subtitles", "en")))
    }

    @Test func aLanguageWithoutUploadedSubtitlesTakesTheAutoGeneratedOnes() async throws {
        let video = try await candidate("video-auto-translation.json", languages: ["ko", "en"])

        let chosen = subtitles(of: video.versions.first { !$0.isAudio })
        #expect(chosen.map(\.language) == ["ko"])
        #expect(chosen.first?.url == (try fixtureURL("video-auto-translation.json", "automatic_captions", "ko-orig")))
    }

    @Test func withNothingInAnyChosenLanguageAnAutoTranslationIntoTheFirstIsUsed() async throws {
        let video = try await candidate("video-auto-translation.json", languages: ["en", "de"])

        let chosen = subtitles(of: video.versions.first { !$0.isAudio })
        #expect(chosen.map(\.language) == ["en"])
        #expect(chosen.first?.url.query()?.contains("tlang=en") == true)
    }

    @Test func subtitlesAreOffUnlessTurnedOnAndAudioNeverGetsThem() async throws {
        let off = try await candidate("video-subtitles-chapters.json", languages: ["en"], downloads: false)
        let on = try await candidate("video-subtitles-chapters.json", languages: ["en"])

        #expect(off.versions.allSatisfy { subtitles(of: $0).isEmpty })
        #expect(on.versions.filter(\.isAudio).allSatisfy { subtitles(of: $0).isEmpty })
        #expect(!subtitles(of: on.versions.first { !$0.isAudio }).isEmpty)
    }
}
